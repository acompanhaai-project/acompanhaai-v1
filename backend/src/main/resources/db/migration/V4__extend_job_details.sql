CREATE TABLE tb_job_skill (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL REFERENCES tb_job(id) ON DELETE CASCADE,
    name VARCHAR(150) NOT NULL CHECK (TRIM(name) <> ''),
    normalized_name VARCHAR(150) NOT NULL CHECK (TRIM(normalized_name) <> ''),
    type VARCHAR(32) NOT NULL CHECK (type IN ('HARD', 'SOFT')),
    source_excerpt TEXT,
    CONSTRAINT uk_job_skill UNIQUE (job_id, type, normalized_name)
);

