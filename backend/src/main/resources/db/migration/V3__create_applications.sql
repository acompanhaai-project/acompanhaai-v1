CREATE TABLE tb_job (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES tb_user(id) ON DELETE CASCADE,
    title VARCHAR(255) NOT NULL,
    company_name VARCHAR(255),
    source_url VARCHAR(2048),
    description TEXT,
    CONSTRAINT uk_job_owner UNIQUE (id, user_id)
);

CREATE TABLE tb_application (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES tb_user(id) ON DELETE CASCADE,
    job_id BIGINT NOT NULL UNIQUE,
    status VARCHAR(32) NOT NULL,
    applied_on DATE,
    notes VARCHAR(5000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_application_job_owner FOREIGN KEY (job_id, user_id)
        REFERENCES tb_job(id, user_id) ON DELETE CASCADE,
    CONSTRAINT ck_application_status CHECK (status IN
        ('SAVED', 'APPLIED', 'SCREENING', 'INTERVIEW', 'OFFER', 'HIRED', 'REJECTED', 'WITHDRAWN')),
    CONSTRAINT ck_saved_date CHECK (status <> 'SAVED' OR applied_on IS NULL)
);

CREATE TABLE tb_application_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES tb_application(id) ON DELETE CASCADE,
    from_status VARCHAR(32),
    to_status VARCHAR(32) NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_application_owner_status ON tb_application(user_id, status, updated_at DESC, id DESC);
CREATE INDEX idx_application_owner_updated ON tb_application(user_id, updated_at DESC, id DESC);
CREATE INDEX idx_job_user ON tb_job(user_id);
CREATE INDEX idx_history_application ON tb_application_status_history(application_id, changed_at, id);
