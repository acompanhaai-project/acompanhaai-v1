CREATE TABLE tb_password_reset_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at TIMESTAMP WITH TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    CONSTRAINT fk_password_reset_user FOREIGN KEY (user_id)
        REFERENCES tb_user(id) ON DELETE CASCADE,
    CONSTRAINT uk_password_reset_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_password_reset_hash_length CHECK (CHAR_LENGTH(token_hash) = 64),
    CONSTRAINT ck_password_reset_expiration CHECK (
        expires_at > created_at AND expires_at <= created_at + INTERVAL '30' MINUTE
    ),
    CONSTRAINT ck_password_reset_used_at CHECK (
        used_at IS NULL OR (used_at >= created_at AND used_at < expires_at)
    )
);

CREATE INDEX ix_password_reset_user_created ON tb_password_reset_token(user_id, created_at DESC, id DESC);
CREATE INDEX ix_password_reset_expiration ON tb_password_reset_token(expires_at);
