CREATE TABLE tb_import_task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES tb_user(id) ON DELETE CASCADE,
    job_id BIGINT,
    input_type VARCHAR(32) NOT NULL CHECK (input_type IN ('URL', 'TEXT')),
    source_url TEXT,
    input_text TEXT,
    collected_text TEXT,
    status VARCHAR(32) NOT NULL CHECK (status IN
        ('PENDING', 'PROCESSING', 'READY_FOR_REVIEW', 'NEEDS_INPUT', 'FAILED', 'COMPLETED')),
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    next_attempt_at TIMESTAMP WITH TIME ZONE,
    locked_until TIMESTAMP WITH TIME ZONE,
    lock_token VARCHAR(36),
    started_at TIMESTAMP WITH TIME ZONE,
    finished_at TIMESTAMP WITH TIME ZONE,
    extractor_provider VARCHAR(100),
    extractor_model VARCHAR(100),
    result_schema_version INTEGER CHECK (result_schema_version > 0),
    extracted_data JSONB,
    error_code VARCHAR(100),
    error_message TEXT,
    reviewed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_import_job_owner FOREIGN KEY (job_id, user_id)
        REFERENCES tb_job(id, user_id) ON DELETE CASCADE,
    CONSTRAINT ck_import_input CHECK (
        (input_type = 'URL' AND source_url IS NOT NULL AND TRIM(source_url) <> '' AND input_text IS NULL)
        OR (input_type = 'TEXT' AND input_text IS NOT NULL AND TRIM(input_text) <> '' AND source_url IS NULL)
    ),
    CONSTRAINT ck_import_completed CHECK (
        status <> 'COMPLETED' OR (job_id IS NOT NULL AND reviewed_at IS NOT NULL)
    ),
    CONSTRAINT ck_import_lock CHECK (
        status <> 'PROCESSING' OR (lock_token IS NOT NULL AND locked_until IS NOT NULL)
    )
);

CREATE INDEX ix_import_user_created ON tb_import_task(user_id, created_at DESC, id DESC);
CREATE INDEX ix_import_job_owner ON tb_import_task(job_id, user_id);
CREATE INDEX ix_import_pending ON tb_import_task(status, next_attempt_at, id);
CREATE INDEX ix_import_expired ON tb_import_task(status, locked_until, id);
